param(
  [switch]$ValidateOnly
)

$ErrorActionPreference = "Stop"

$tauriRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot "..\..\..\..")).Path
$configPath = Join-Path $tauriRoot "tauri.conf.json"
$runtimeConfigPath = Join-Path $tauriRoot "target\windows-runtime\tauri.generated.conf.json"
$releaseRoot = Join-Path $tauriRoot "target\release"
$mainBinaryPath = Join-Path $releaseRoot "pinvou3-tauri.exe"
$stagingRoot = Join-Path $releaseRoot "nsis-stage"
$stagingResourcesRoot = Join-Path $stagingRoot "resources"
$stagingConfigPath = Join-Path $stagingRoot "tauri.nsis-stage.conf.json"
$stagingInstallerHooksPath = Join-Path $stagingRoot "installer-hooks.nsh"
$manifestPath = Join-Path $stagingRoot "manifest.json"
$baseInstallerHooksPath = Join-Path $tauriRoot "packaging\windows\nsis\installer-hooks.nsh"
# The generated installer hooks File-reference the VC++ redistributable that
# windows-installer.js stages for build/bundle runs; validate its presence so
# standalone -ValidateOnly runs fail here instead of at makensis.
$vcRedistPath = Join-Path $tauriRoot "target\windows-runtime\nsis\vc_redist\VC_redist.x64.exe"

function Assert-ChildPath {
  param(
    [string]$Root,
    [string]$Path
  )

  $rootFull = [System.IO.Path]::GetFullPath($Root).TrimEnd('\') + '\'
  $pathFull = [System.IO.Path]::GetFullPath($Path).TrimEnd('\') + '\'
  if (-not $pathFull.StartsWith($rootFull, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "Refusing to use a path outside the staging root: $Path"
  }
}

function Write-Utf8WithoutBom {
  param(
    [string]$Path,
    [string]$Content
  )

  $encoding = New-Object System.Text.UTF8Encoding($false)
  [System.IO.File]::WriteAllText($Path, $Content, $encoding)
}

function Get-StagedRelativeFiles {
  if (-not (Test-Path -LiteralPath $stagingResourcesRoot -PathType Container)) {
    return @()
  }

  $prefix = [System.IO.Path]::GetFullPath($stagingResourcesRoot).TrimEnd('\') + '\'
  return @(
    Get-ChildItem -LiteralPath $stagingResourcesRoot -Recurse -File -Force |
      ForEach-Object {
        $_.FullName.Substring($prefix.Length).Replace('\', '/')
      } |
      Sort-Object
  )
}

function Get-StagedRelativeDirectories {
  if (-not (Test-Path -LiteralPath $stagingResourcesRoot -PathType Container)) {
    return @()
  }

  $prefix = [System.IO.Path]::GetFullPath($stagingResourcesRoot).TrimEnd('\') + '\'
  return @(
    Get-ChildItem -LiteralPath $stagingResourcesRoot -Recurse -Directory -Force |
      ForEach-Object {
        $_.FullName.Substring($prefix.Length).Replace('\', '/')
      } |
      Sort-Object `
        @{ Expression = { $_.Split('/').Count }; Descending = $true }, `
        @{ Expression = { $_ }; Descending = $false }
  )
}

function Get-StagedResourceBytes {
  if (-not (Test-Path -LiteralPath $stagingResourcesRoot -PathType Container)) {
    return [long]0
  }

  $measurement = Get-ChildItem -LiteralPath $stagingResourcesRoot -Recurse -File -Force |
    Measure-Object -Property Length -Sum
  return [long]$measurement.Sum
}

function ConvertTo-NsisQuotedLiteral {
  param([string]$Value)

  return $Value.Replace('$', '$$').Replace('"', '$\"')
}

function New-StagingInstallerHooksContent {
  param([long]$StagedResourceBytes)

  if (-not (Test-Path -LiteralPath $baseInstallerHooksPath -PathType Leaf)) {
    throw "Base NSIS installer hooks were not found: $baseInstallerHooksPath"
  }

  $resourceGlob = ConvertTo-NsisQuotedLiteral -Value (Join-Path $stagingResourcesRoot "*.*")
  $stagedResourceSizeKiB = [long][Math]::Ceiling($StagedResourceBytes / 1KB)
  $generatedLines = [System.Collections.Generic.List[string]]::new()
  $generatedLines.Add("; Generated by stage-resources.ps1. Do not edit.")
  $generatedLines.Add(('!define PINVOU_STAGED_RESOURCES_SIZE_KIB {0}' -f $stagedResourceSizeKiB))
  $generatedLines.Add("")
  $generatedLines.Add("!macro PINVOU_INSTALL_STAGED_RESOURCES")
  $generatedLines.Add('  SetOutPath "$INSTDIR"')
  $generatedLines.Add(('  File /a /r "{0}"' -f $resourceGlob))
  $generatedLines.Add("!macroend")
  $generatedLines.Add("")
  $generatedLines.Add("!macro PINVOU_UNINSTALL_STAGED_RESOURCES")

  foreach ($relativeFile in Get-StagedRelativeFiles) {
    $targetPath = ConvertTo-NsisQuotedLiteral -Value $relativeFile.Replace('/', '\')
    $generatedLines.Add(('  Delete /REBOOTOK "$INSTDIR\{0}"' -f $targetPath))
  }
  foreach ($relativeDirectory in Get-StagedRelativeDirectories) {
    $targetPath = ConvertTo-NsisQuotedLiteral -Value $relativeDirectory.Replace('/', '\')
    $generatedLines.Add(('  RMDir /REBOOTOK "$INSTDIR\{0}"' -f $targetPath))
  }
  $generatedLines.Add("!macroend")
  $generatedLines.Add("")

  $baseHooks = [System.IO.File]::ReadAllText($baseInstallerHooksPath, [System.Text.Encoding]::UTF8).TrimStart([char]0xFEFF)
  return (($generatedLines -join "`r`n") + "`r`n" + $baseHooks.TrimEnd() + "`r`n")
}

function Copy-DirectoryContents {
  param(
    [string]$Source,
    [string]$Destination
  )

  New-Item -ItemType Directory -Path $Destination -Force | Out-Null
  $robocopyOutput = & robocopy.exe $Source $Destination /E /COPY:DAT /DCOPY:DAT /R:2 /W:1 /NFL /NDL /NJH /NJS /NP
  if ($LASTEXITCODE -gt 7) {
    $robocopyTail = (@($robocopyOutput) | Select-Object -Last 5 | ForEach-Object { "$_" }) -join " | "
    throw "Failed to stage resource directory (robocopy exit code $LASTEXITCODE): $Source. Output tail: $robocopyTail"
  }
}

if ($ValidateOnly) {
  foreach ($requiredPath in @($mainBinaryPath, $stagingResourcesRoot, $stagingConfigPath, $stagingInstallerHooksPath, $manifestPath)) {
    if (-not (Test-Path -LiteralPath $requiredPath)) {
      throw "NSIS staging is incomplete. Run 'npm run build:nsis:stage' first. Missing: $requiredPath"
    }
  }
  if (-not (Test-Path -LiteralPath $vcRedistPath)) {
    throw "NSIS staging is incomplete: the VC++ redistributable is missing. Run 'npm run build:nsis:stage' first (build.js stages it): $vcRedistPath"
  }

  $manifestJson = [System.IO.File]::ReadAllText($manifestPath, [System.Text.Encoding]::UTF8)
  $manifest = ConvertFrom-Json -InputObject $manifestJson
  if ([int]$manifest.schemaVersion -ne 2) {
    throw "NSIS staging manifest schema is outdated. Run 'npm run build:nsis:stage' again."
  }
  if ([string]$manifest.installerHooks -ne "target/release/nsis-stage/installer-hooks.nsh") {
    throw "NSIS staging manifest does not reference the generated installer hooks."
  }
  $expectedFiles = @($manifest.files | Sort-Object)
  $actualFiles = @(Get-StagedRelativeFiles)
  $difference = @(Compare-Object -ReferenceObject $expectedFiles -DifferenceObject $actualFiles)
  if ($difference.Count -ne 0) {
    $preview = ($difference | Select-Object -First 10 | ForEach-Object { "$($_.SideIndicator) $($_.InputObject)" }) -join "; "
    throw "NSIS staging file set changed after collection. Run 'npm run build:nsis:stage' again. Differences: $preview"
  }

  $actualStagedBytes = Get-StagedResourceBytes
  $expectedInstallerHooks = New-StagingInstallerHooksContent -StagedResourceBytes $actualStagedBytes
  $actualInstallerHooks = [System.IO.File]::ReadAllText($stagingInstallerHooksPath, [System.Text.Encoding]::UTF8)
  if ($actualInstallerHooks -ne $expectedInstallerHooks) {
    throw "NSIS staging installer hooks changed after collection. Run 'npm run build:nsis:stage' again."
  }

  $stagingConfigJson = [System.IO.File]::ReadAllText($stagingConfigPath, [System.Text.Encoding]::UTF8)
  $stagingConfig = ConvertFrom-Json -InputObject $stagingConfigJson
  if ([string]$stagingConfig.bundle.windows.nsis.installerHooks -ne "target/release/nsis-stage/installer-hooks.nsh") {
    throw "NSIS staging config does not reference the generated installer hooks."
  }
  $resourceProperties = @($stagingConfig.bundle.resources.PSObject.Properties)
  $expectedResourceSources = @($manifest.mappings | ForEach-Object { [string]$_.source } | Sort-Object)
  $actualResourceSources = @($resourceProperties | ForEach-Object { $_.Name } | Sort-Object)
  $resourceSourceDifference = @(Compare-Object -ReferenceObject $expectedResourceSources -DifferenceObject $actualResourceSources)
  if ($resourceSourceDifference.Count -ne 0 -or @($resourceProperties | Where-Object { $null -ne $_.Value }).Count -ne 0) {
    throw "NSIS staging config must only remove the original Tauri resource mappings."
  }

  Write-Host ("Validated NSIS staging: {0} resource files" -f $actualFiles.Count)
  exit 0
}

if (-not (Test-Path -LiteralPath $mainBinaryPath -PathType Leaf)) {
  throw "Release executable not found. Run the Tauri --no-bundle build first: $mainBinaryPath"
}

$configJson = [System.IO.File]::ReadAllText($configPath, [System.Text.Encoding]::UTF8)
$config = ConvertFrom-Json -InputObject $configJson
if (-not (Test-Path -LiteralPath $runtimeConfigPath -PathType Leaf)) {
  throw "Windows runtime staging config is missing. Run src-tauri/packaging/windows/runtime/scripts/stage-runtime.ps1 first: $runtimeConfigPath"
}
$runtimeConfigJson = [System.IO.File]::ReadAllText($runtimeConfigPath, [System.Text.Encoding]::UTF8)
$runtimeConfig = ConvertFrom-Json -InputObject $runtimeConfigJson
if ($null -eq $config.bundle.resources -or $null -eq $runtimeConfig.bundle.resources) {
  throw "bundle.resources is missing from $configPath or $runtimeConfigPath"
}
$resourceProperties = @($config.bundle.resources.PSObject.Properties) + @($runtimeConfig.bundle.resources.PSObject.Properties)
if ($resourceProperties.Count -eq 0) {
  throw "No bundle.resources mappings were found in $configPath"
}

Assert-ChildPath -Root $releaseRoot -Path $stagingRoot
Remove-Item -LiteralPath $stagingRoot -Recurse -Force -ErrorAction SilentlyContinue
if (Test-Path -LiteralPath $stagingRoot) {
  throw "Failed to clear the NSIS staging root (a staged file may be locked): $stagingRoot"
}
New-Item -ItemType Directory -Path $stagingResourcesRoot -Force | Out-Null

$resourceOverrides = [ordered]@{}
$mappingManifest = @()

foreach ($property in $resourceProperties) {
  $sourceSpec = [string]$property.Name
  $destinationSpec = [string]$property.Value

  if ($sourceSpec -match '[*?\[]') {
    throw "Glob resource mappings are not supported by the NSIS staging script: $sourceSpec"
  }

  $sourcePath = [System.IO.Path]::GetFullPath((Join-Path $tauriRoot $sourceSpec))
  # Runtime overlay source keys end in a trailing separator; a trailing
  # backslash before the closing quote corrupts the native robocopy argument
  # on Windows PowerShell 5.1 (the \" is parsed as a literal quote), so strip
  # it before any native invocation. robocopy /E copies the directory itself.
  $sourcePath = $sourcePath.TrimEnd('\', '/')
  if (-not (Test-Path -LiteralPath $sourcePath)) {
    throw "Configured bundle resource does not exist: $sourceSpec ($sourcePath)"
  }

  $destinationPath = [System.IO.Path]::GetFullPath((Join-Path $stagingResourcesRoot $destinationSpec))
  $destinationPath = $destinationPath.TrimEnd('\', '/')
  Assert-ChildPath -Root $stagingResourcesRoot -Path $destinationPath

  if (Test-Path -LiteralPath $sourcePath -PathType Container) {
    Copy-DirectoryContents -Source $sourcePath -Destination $destinationPath
  } else {
    $destinationParent = Split-Path -Parent $destinationPath
    New-Item -ItemType Directory -Path $destinationParent -Force | Out-Null
    Copy-Item -LiteralPath $sourcePath -Destination $destinationPath -Force
  }

  # Tauri merges --config values into tauri.conf.json. Null removes each original
  # source entry so Tauri never enumerates or verifies pre-signed staged binaries.
  $resourceOverrides[$sourceSpec] = $null
  $mappingManifest += [ordered]@{
    source = $sourceSpec
    destination = $destinationSpec
  }
}

$stagedFiles = @(Get-StagedRelativeFiles)
$stagedBytes = Get-StagedResourceBytes

$stagingInstallerHooks = New-StagingInstallerHooksContent -StagedResourceBytes $stagedBytes
Write-Utf8WithoutBom -Path $stagingInstallerHooksPath -Content $stagingInstallerHooks

$stagingConfig = [ordered]@{
  bundle = [ordered]@{
    resources = $resourceOverrides
    windows = [ordered]@{
      nsis = [ordered]@{
        installerHooks = "target/release/nsis-stage/installer-hooks.nsh"
      }
    }
  }
}
Write-Utf8WithoutBom -Path $stagingConfigPath -Content ($stagingConfig | ConvertTo-Json -Depth 8)

$manifest = [ordered]@{
  schemaVersion = 2
  generatedAtUtc = [DateTime]::UtcNow.ToString("o")
  appVersion = [string]$config.version
  mainBinary = "target/release/pinvou3-tauri.exe"
  installerHooks = "target/release/nsis-stage/installer-hooks.nsh"
  resourceFileCount = $stagedFiles.Count
  resourceBytes = [long]$stagedBytes
  mappings = $mappingManifest
  files = $stagedFiles
}
Write-Utf8WithoutBom -Path $manifestPath -Content ($manifest | ConvertTo-Json -Depth 8)

Write-Host ("Collected NSIS resources: {0} files ({1:N2} MiB)" -f $stagedFiles.Count, ($stagedBytes / 1MB))
Write-Host "Staging directory: $stagingRoot"
Write-Host "Main executable: $mainBinaryPath"
